#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const crypto = require('crypto');
const matter = require('gray-matter');

const BLOG_DIR = path.join(__dirname, '../public/blog');
const MANIFEST_PATH = path.join(__dirname, '../public/blog-posts.json');
const VERSION_PATH = path.join(__dirname, '../src/blogVersion.js');
const MANIFEST_ONLY = process.argv.includes('--manifest-only');

// IMPORTANT: This must stay byte-for-byte identical to generateSlug() in src/App.jsx.
// The manifest's `slug` field is the single source of truth for blog post URLs —
// App.jsx consumes it directly instead of recalculating, and sitemap.xml should be
// generated from these same values, so the three never drift out of sync again.
const generateSlug = (title) => {
  return title
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
};

// gray-matter turns unquoted YAML dates into Date objects; store plain YYYY-MM-DD.
const toIsoDate = (value) => {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value).slice(0, 10);
};

console.log('📝 Generating blog manifest...');

try {
  // Read all markdown files from blog directory (exclude template files)
  const files = fs.readdirSync(BLOG_DIR).filter(file =>
    file.endsWith('.md') &&
    !file.includes('TEMPLATE') &&
    !file.includes('template')
  );

  if (files.length === 0) {
    console.log('⚠️  No markdown files found in public/blog/');
    process.exit(0);
  }

  // Extract metadata from each post
  const manifest = files.map(file => {
    const filePath = path.join(BLOG_DIR, file);
    const content = fs.readFileSync(filePath, 'utf-8');
    const { data, content: bodyContent } = matter(content);

    // Optional SEO front matter (all safe to omit):
    //   seoTitle:        <title> tag override (keeps the H1 and URL slug unchanged)
    //   metaDescription: meta description override (defaults to excerpt)
    //   updated:         YYYY-MM-DD of the last meaningful edit (schema dateModified, sitemap lastmod)
    //   faq:             list of { q, a } — rendered as an FAQ section + FAQPage schema
    return {
      // The id comes from the filename prefix (e.g. 008_...md -> 8). Don't trust the
      // front-matter value: YAML reads a leading-zero id like 010 as octal (= 8)
      // and leaves 008 as the string "008".
      id: parseInt(file.slice(0, 3), 10) || Number(data.id),
      filename: file,
      title: data.title,
      slug: generateSlug(data.title),
      date: toIsoDate(data.date),
      updated: data.updated ? toIsoDate(data.updated) : undefined,
      excerpt: data.excerpt,
      seoTitle: data.seoTitle || undefined,
      metaDescription: data.metaDescription || undefined,
      heroImage: data.heroImage,
      categories: data.categories || [],
      tags: data.tags || [],
      faq: Array.isArray(data.faq) ? data.faq.filter((item) => item && item.q && item.a) : undefined
    };
  });

  // Sort by date descending
  manifest.sort((a, b) => new Date(b.date) - new Date(a.date));

  // Write manifest file
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2));
  console.log(`✅ Manifest generated: ${manifest.length} post(s) found`);

  // Content version for cache-busting. The app fetches /blog-posts.json?v=<version> and
  // each post's markdown with the same ?v=, so a browser or Googlebot's renderer can never
  // pair a new page with an old cached manifest (which used to make a brand-new post look
  // like "not found" and get a client-side noindex). Generated, not committed.
  const hash = crypto.createHash('sha1');
  hash.update(JSON.stringify(manifest));
  files.slice().sort().forEach((file) => hash.update(fs.readFileSync(path.join(BLOG_DIR, file))));
  fs.writeFileSync(VERSION_PATH, `// Generated by scripts/publish-blog.js. Do not edit.\nexport const BLOG_VERSION = '${hash.digest('hex').slice(0, 12)}';\n`);

  // Only commit and push if not in manifest-only mode
  if (!MANIFEST_ONLY) {
    console.log('\n📤 Committing to Git...');

    try {
      execSync('git add public/blog public/blog-posts.json', { stdio: 'inherit' });
      execSync('git commit -m "📝 Publish new blog posts"', { stdio: 'inherit' });

      console.log('\n🚀 Pushing to GitHub...');
      execSync('git push origin main', { stdio: 'inherit' });

      console.log('\n✨ Done! Netlify will auto-deploy in a few moments.');
    } catch (gitError) {
      console.log('\n⚠️  Git operation warning:');
      console.log('   Make sure you\'re in the repo directory and have git configured.');
      console.log('   You can manually run: git add public/blog public/blog-posts.json && git commit -m "📝 Publish blog posts" && git push origin main');
      process.exit(1);
    }
  }
} catch (error) {
  console.error('❌ Error:', error.message);
  process.exit(1);
}
